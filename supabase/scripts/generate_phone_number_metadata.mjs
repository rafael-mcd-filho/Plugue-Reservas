// Rebuild the pinned SQL numbering plans after an intentional libphonenumber update.
// No network or database access. Input is the installed, lockfile-pinned max metadata.
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const metadata = JSON.parse(await readFile(resolve(root, 'node_modules/libphonenumber-js/metadata.max.json'), 'utf8'));
const { version } = JSON.parse(await readFile(resolve(root, 'node_modules/libphonenumber-js/package.json'), 'utf8'));
if (version !== '1.13.15') throw new Error('Library version changed. Create a new numbered migration and review/rebuild dependent indexes; do not overwrite an applied migration.');
if (metadata.version !== 4) throw new Error('Metadata layout changed: review source/metadata.js before regenerating SQL.');

const byCallingCode = {};
const countryCallingCode = Object.fromEntries(Object.entries(metadata.countries).map(([country, plan]) => [country, plan[0]]));
for (const [country, plan] of [...Object.entries(metadata.countries), ...Object.entries(metadata.nonGeographic ?? {})]) {
  const types = Array.isArray(plan[11])
    ? plan[11].filter((type) => Array.isArray(type) && type[0]).map((type) => ({ pattern: type[0], lengths: type[1] || plan[3] }))
    : [];
  (byCallingCode[plan[0]] ??= []).push({ country, pattern: plan[2], lengths: plan[3], types });
}

const sql = `-- Generated by supabase/scripts/generate_phone_number_metadata.mjs.
-- Source: libphonenumber-js ${version}, metadata.max.json v${metadata.version} (MIT).
-- Number plan patterns/possible lengths match the library's getNumberType/isValid rules.
-- No customer data is read or changed by this migration.
CREATE OR REPLACE FUNCTION public._phone_numbering_plans(_calling_code text)
RETURNS jsonb LANGUAGE sql IMMUTABLE SET search_path = public, pg_temp AS $function$
  SELECT $metadata$${JSON.stringify(byCallingCode)}$metadata$::jsonb -> _calling_code;
$function$;

CREATE OR REPLACE FUNCTION public.phone_country_calling_code(_country text)
RETURNS text LANGUAGE sql IMMUTABLE SET search_path = public, pg_temp AS $function$
  SELECT $metadata$${JSON.stringify(countryCallingCode)}$metadata$::jsonb ->> upper(_country);
$function$;

CREATE OR REPLACE FUNCTION public.phone_e164_default_country(_phone text)
RETURNS text LANGUAGE plpgsql IMMUTABLE SET search_path = public, pg_temp AS $$
DECLARE _plans jsonb;
BEGIN
  FOR _size IN 1..3 LOOP
    _plans := public._phone_numbering_plans(substring(_phone FROM 2 FOR _size));
    IF _plans IS NOT NULL THEN
      IF jsonb_array_length(_plans) = 1 AND length(_plans->0->>'country') = 2 THEN RETURN _plans->0->>'country'; END IF;
      RETURN NULL;
    END IF;
  END LOOP;
  RETURN NULL;
END;
$$;

CREATE OR REPLACE FUNCTION public.is_valid_phone_e164(_phone text)
RETURNS boolean LANGUAGE plpgsql IMMUTABLE SET search_path = public, pg_temp AS $$
DECLARE _digits text; _national text; _plans jsonb; _plan jsonb; _type jsonb; _calling_code_length integer;
BEGIN
  IF _phone IS NULL OR _phone !~ '^\\+[1-9][0-9]{6,14}$' THEN RETURN false; END IF;
  _digits := substring(_phone FROM 2);
  FOR _size IN 1..3 LOOP
    _plans := public._phone_numbering_plans(left(_digits, _size));
    IF _plans IS NOT NULL THEN _calling_code_length := _size; EXIT; END IF;
  END LOOP;
  IF _plans IS NULL THEN RETURN false; END IF;
  _national := substring(_digits FROM _calling_code_length + 1);
  FOR _plan IN SELECT value FROM jsonb_array_elements(_plans) LOOP
    IF NOT EXISTS (SELECT 1 FROM jsonb_array_elements_text(_plan->'lengths') l(value) WHERE value::integer = length(_national))
      OR _national !~ ('^(?:' || (_plan->>'pattern') || ')$') THEN CONTINUE; END IF;
    IF jsonb_array_length(_plan->'types') = 0 THEN RETURN true; END IF;
    FOR _type IN SELECT value FROM jsonb_array_elements(_plan->'types') LOOP
      IF EXISTS (SELECT 1 FROM jsonb_array_elements_text(_type->'lengths') l(value) WHERE value::integer = length(_national))
        AND _national ~ ('^(?:' || (_type->>'pattern') || ')$') THEN RETURN true; END IF;
    END LOOP;
  END LOOP;
  RETURN false;
END;
$$;

COMMENT ON FUNCTION public.is_valid_phone_e164(text) IS 'Number-plan validation generated from libphonenumber-js ${version} max metadata; regenerate intentionally with package upgrades.';
REVOKE ALL ON FUNCTION public._phone_numbering_plans(text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public._phone_numbering_plans(text), public.is_valid_phone_e164(text),
  public.phone_country_calling_code(text), public.phone_e164_default_country(text) TO anon, authenticated, service_role;
`;
const destination = resolve(root, 'supabase/migrations/20261019115000_add_phone_number_metadata.sql');
await writeFile(destination, sql);
process.stdout.write(`Generated SQL phone metadata from libphonenumber-js ${version}: ${Object.keys(byCallingCode).length} calling codes.\n`);
